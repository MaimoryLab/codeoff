  String t(String key, [Map<String, String> args = const {}]) {
    var value =
        _values[locale.languageCode]?[key] ?? _values['en']![key] ?? key;
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }
